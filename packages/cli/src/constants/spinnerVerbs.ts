export function getSpinnerVerbs(): string[] {
  const settings = getInitialSettings()
  const config = settings.spinnerVerbs

  // If user has custom verbs configured, respect that
  if (config) {
    if (config.mode === 'replace') {
      return config.verbs.length > 0 ? config.verbs : getLanguageSpecificVerbs()
    }
    return [...getLanguageSpecificVerbs(), ...config.verbs]
  }

  return getLanguageSpecificVerbs()
}

/**
 * Get language-specific spinner verbs
 */
function getLanguageSpecificVerbs(): string[] {
  const lang = getUILanguage()
  if (lang === 'zh') {
    return SPINNER_VERBS_ZH
  }
  return SPINNER_VERBS
}

